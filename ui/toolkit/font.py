# Fallback glyph for unmapped characters (filled block)
FALLBACK_GLYPH = [0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00]

BASE_GLYPH_WIDTH = 8
BASE_GLYPH_HEIGHT = 8


class FontRenderer:
    """
    Renders text strings to BGRA pixel buffers.

    Uses a built-in 8x8 bitmap font, scaled to match the requested
    FontStyle size. Supports basic text layout (single-line and
    multi-line with word wrapping).
    """

    def __init__(self):
        self._glyph_cache: dict[tuple, bytearray] = {}

    def render_text(self, text: str, style: FontStyle,
                    color: Color) -> RenderedText:
        """Render a single line of text."""
        if not text:
            return RenderedText(data=bytearray(), width=0,
                                height=style.line_height, stride=0)

        scale = max(1, style.size // BASE_GLYPH_HEIGHT)
        glyph_w = BASE_GLYPH_WIDTH * scale
        glyph_h = BASE_GLYPH_HEIGHT * scale
        spacing = style.spacing * scale

        total_w = len(text) * (glyph_w + spacing) - spacing
        total_h = style.line_height
        stride = total_w * 4

        buf = bytearray(stride * total_h)

        x = 0
        for ch in text:
            self._draw_glyph(buf, stride, total_h, x, 0,
                             ch, scale, color)
            x += glyph_w + spacing

        return RenderedText(data=buf, width=total_w,
                            height=total_h, stride=stride)

    def render_wrapped(self, text: str, style: FontStyle, color: Color,
                       max_width: int) -> RenderedText:
        """Render text with word wrapping within max_width pixels."""
        scale = max(1, style.size // BASE_GLYPH_HEIGHT)
        glyph_w = BASE_GLYPH_WIDTH * scale
        spacing = style.spacing * scale
        char_advance = glyph_w + spacing

        if char_advance <= 0 or max_width <= 0:
            return RenderedText(data=bytearray(), width=0,
                                height=style.line_height, stride=0)

        # Word wrap
        lines = self._word_wrap(text, max_width, char_advance)

        if not lines:
            return RenderedText(data=bytearray(), width=0,
                                height=style.line_height, stride=0)

        line_h = style.line_height
        total_h = line_h * len(lines)
        total_w = max_width
        stride = total_w * 4

        buf = bytearray(stride * total_h)

        for row, line in enumerate(lines):
            x = 0
            for ch in line:
                if x + glyph_w > total_w:
                    break
                self._draw_glyph(buf, stride, total_h, x,
                                 row * line_h, ch, scale, color)
                x += char_advance

        return RenderedText(data=buf, width=total_w,
                            height=total_h, stride=stride)

    def measure_text(self, text: str, style: FontStyle) -> tuple[int, int]:
        """Measure text dimensions without rendering. Returns (width, height)."""
        if not text:
            return (0, style.line_height)
        scale = max(1, style.size // BASE_GLYPH_HEIGHT)
        glyph_w = BASE_GLYPH_WIDTH * scale
        spacing = style.spacing * scale
        width = len(text) * (glyph_w + spacing) - spacing
        return (width, style.line_height)

    def _word_wrap(self, text: str, max_width: int,
                   char_advance: int) -> list[str]:
        """Break text into lines that fit within max_width."""
        chars_per_line = max(1, (max_width + char_advance - 1) // char_advance)
        words = text.split(' ')
        lines = []
        current = ""

        for word in words:
            if not current:
                current = word
            elif len(current) + 1 + len(word) <= chars_per_line:
                current += " " + word
            else:
                lines.append(current)
                current = word

        if current:
            lines.append(current)

        return lines

    def _draw_glyph(self, buf: bytearray, stride: int, buf_h: int,
                    x: int, y: int, ch: str, scale: int, color: Color):
        """Draw a single glyph into the buffer."""
        code = ord(ch)
        glyph = FONT_8X8.get(code, FALLBACK_GLYPH)
        b, g, r, a = color.bgra

        for row in range(BASE_GLYPH_HEIGHT):
            bits = glyph[row]
            for col in range(BASE_GLYPH_WIDTH):
                if bits & (0x80 >> col):
                    # Draw scaled pixel
                    for sy in range(scale):
                        py = y + row * scale + sy
                        if py < 0 or py >= buf_h:
                            continue
                        for sx in range(scale):
                            px = x + col * scale + sx
                            offset = py * stride + px * 4
                            if offset + 3 < len(buf):
                                buf[offset] = b
                                buf[offset + 1] = g
                                buf[offset + 2] = r
                                buf[offset + 3] = a
