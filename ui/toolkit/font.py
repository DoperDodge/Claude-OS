"""
Claude-OS Bitmap Font Renderer

Renders text to pixel buffers using a built-in bitmap font.
No external libraries (Cairo, FreeType, etc.) required — works on
bare-metal embedded Linux with just Python.

The built-in font covers ASCII printable characters (0x20-0x7E)
at multiple sizes using scaled bitmaps. Each glyph is stored as a
compact bit pattern.

Usage:
    renderer = FontRenderer()
    buf = renderer.render_text("Hello", font_style, color)
    # buf is a bytearray of BGRA pixels, width/height returned
"""

import struct
from dataclasses import dataclass

from theme import Color, FontStyle


@dataclass
class GlyphMetrics:
    """Metrics for a rendered glyph."""
    width: int
    height: int
    advance: int  # Horizontal advance to next glyph
    bearing_x: int = 0
    bearing_y: int = 0


@dataclass
class RenderedText:
    """Result of rendering a text string."""
    data: bytearray    # BGRA pixel data
    width: int
    height: int
    stride: int        # bytes per row


